use printpdf::lopdf::{Document, Object, content::Content};
use snipe_code::audit::{self, AuditResult, Finding};
use std::{fs, path::PathBuf, process::Command};

struct Fixture(PathBuf);

impl Fixture {
    fn new() -> Self {
        let root = std::env::var_os("TMPDIR")
            .map(PathBuf::from)
            .unwrap_or_else(std::env::temp_dir)
            .join(format!("snipe-pdf-{}", uuid::Uuid::new_v4()));
        fs::create_dir_all(&root).unwrap();
        Self(root)
    }
}
impl Drop for Fixture {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn export(count: usize) -> (Fixture, Vec<Finding>) {
    let fixture = Fixture::new();
    let findings: Vec<_> = (0..count)
        .map(|i| Finding {
            severity: "LOW".into(),
            category: format!("Category{i:04}"),
            file: format!("src/file{i:04}_{}.rs", "a".repeat(100)),
            line: i + 1,
            description: "Potential SQL injection: string concatenation in query".into(),
        })
        .collect();
    let result = AuditResult {
        exported_files: vec![],
        findings: findings.clone(),
        high: 0,
        medium: 0,
        low: count,
        highest_severity: if count == 0 { None } else { Some("LOW".into()) },
        policy_failed: false,
        detected_scopes: vec![],
        evaluated_rule_groups: vec![],
        exclusions: vec![],
        sast: vec![],
        sca: None,
    };
    let json = audit::render_scan_json(&fixture.0, result).unwrap();
    let input = fixture.0.join("scan.json");
    fs::write(&input, json).unwrap();
    audit::export_scan_json(&input, "pdf", &fixture.0).unwrap();
    (fixture, findings)
}

fn number(value: &Object) -> f32 {
    match value {
        Object::Integer(n) => *n as f32,
        Object::Real(n) => *n,
        _ => panic!("expected numeric PDF coordinate: {value:?}"),
    }
}

#[test]
fn page_coordinates_and_footers_cover_zero_one_and_many_findings() {
    for count in [0, 1, 100] {
        let (fixture, _) = export(count);
        let doc = Document::load(fixture.0.join("Audit_Report.pdf")).unwrap();
        let pages = doc.get_pages();
        if count == 100 {
            assert!(pages.len() > 1);
        }
        for page in pages.values() {
            let content = Content::decode(&doc.get_page_content(*page).unwrap()).unwrap();
            let mut footer = false;
            let mut text_positions = 0;
            for op in content.operations {
                if op.operator == "Td" {
                    let x = number(&op.operands[0]) * 25.4 / 72.0;
                    let y = number(&op.operands[1]) * 25.4 / 72.0;
                    assert!((19.99..=190.0).contains(&x), "x={x}");
                    assert!((19.99..=277.0).contains(&y), "y={y}");
                    text_positions += 1;
                }
                if op.operator == "Tj" {
                    let bytes = op.operands[0].as_str().unwrap();
                    assert!(bytes.len() <= 70, "line length {}", bytes.len());
                    footer |= Document::decode_text(Some("WinAnsiEncoding"), bytes)
                        == "Report generated by SNIPE-CODE CLI";
                }
            }
            assert!(text_positions > 0);
            assert!(footer, "missing footer");
        }
    }
}

#[test]
fn extracted_text_preserves_every_finding_across_pages() {
    let (fixture, findings) = export(100);
    let output = match Command::new("pdftotext")
        .current_dir(&fixture.0)
        .args(["-raw", "Audit_Report.pdf", "-"])
        .output()
    {
        Ok(output) => output,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            eprintln!("NOT RUN: pdftotext unavailable");
            return;
        }
        Err(error) => panic!("pdftotext: {error}"),
    };
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    let text = String::from_utf8(output.stdout).unwrap();
    let text = text.replace("Report generated by SNIPE-CODE CLI", "");
    let compact: String = text.chars().filter(|ch| !ch.is_whitespace()).collect();
    for (index, finding) in findings.iter().enumerate() {
        let expected = format!(
            "{}. {} [{}]File: {} (line {})Description: {}",
            index + 1,
            finding.category,
            finding.severity,
            finding.file,
            finding.line,
            finding.description
        );
        let compact_expected: String = expected.chars().filter(|ch| !ch.is_whitespace()).collect();
        assert!(compact.contains(&compact_expected), "missing {expected}");
    }
}
